const serviceBrandKeywords = ['Nain CSC', 'Nain CSC Center', 'Jind CSC', 'Danoda CSC', 'Nain Photostate Danoda']

function normalizeServiceValue(value) {
  if (Array.isArray(value)) {
    return value.map(normalizeServiceValue)
  }

  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, nestedValue]) => [key, normalizeServiceValue(nestedValue)]))
  }

  if (typeof value !== 'string') {
    return value
  }

  return serviceBrandReplacements.reduce((text, [pattern, replacement]) => text.replace(pattern, replacement), value)
}

servicesData.forEach((service, index) => {
  const normalizedService = normalizeServiceValue(service)

  servicesData[index] = {
    ...normalizedService,
    keywords: [...new Set([...(normalizedService.keywords || []), ...serviceBrandKeywords])],
  }
})

/**
 * Get service data by slug
 */
export function getServiceBySlug(slug) {
  return servicesData.find((s) => s.slug === slug) || null
}

/**
 * Get all service slugs for static generation
 */
export function getAllServiceSlugs() {
  return servicesData.map((s) => s.slug)
}

/**
 * Map from old external URL to new internal service slug
 */
export function getSlugByExternalUrl(url) {
  const service = servicesData.find((s) => s.externalUrl === url)
  return service ? service.slug : null
}
